def expand_query(query: str) -> str:
    """在原始查询后追加命中的规范术语，去重并保持稳定顺序。"""
    query = (query or "").strip()
    if not query:
        return ""

    additions: list[str] = []
    for colloquial, legal_terms in _EXPANSIONS:
        if colloquial not in query:
            continue
        for term in legal_terms:
            if term and term not in query and term not in additions:
                additions.append(term)

    if not additions:
        return query
    return f"{query} {' '.join(additions)}"
